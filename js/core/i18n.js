/* Bahasa aktif. Dibaca dari localStorage supaya pilihannya bertahan
   antar kunjungan; "id" kalau belum pernah dipilih. */
let activeLang = "id";
try {
  const tersimpan = localStorage.getItem(I18N_LANG_KEY);
  if (tersimpan && I18N[tersimpan]) activeLang = tersimpan;
} catch (e) {
  /* localStorage bisa ditolak di mode privat — bahasa bawaan saja. */
}

/* Terjemahan satu kunci.

   Kunci yang belum ada TIDAK dikosongkan: ia jatuh ke bahasa Indonesia
   dulu, lalu ke kuncinya sendiri. Layar yang menampilkan
   "hscode.add.help" memang jelek, tapi jauh lebih mudah ditemukan
   daripada bidang kosong tanpa petunjuk apa yang hilang. */
function t(kunci, ganti) {
  const kamus = I18N[activeLang] || I18N.id;
  let teks = kamus[kunci];
  if (teks == null) teks = I18N.id[kunci];
  if (teks == null) return kunci;
  if (ganti) {
    Object.keys(ganti).forEach((k) => {
      teks = teks.split("{" + k + "}").join(ganti[k]);
    });
  }
  return teks;
}

/* Menyapu seluruh halaman dan mengisi ulang tiap elemen ber-data-i18n.

   data-i18n       -> isi elemen (HTML, supaya <b> di dalam kalimat
                      panduan ikut terbawa)
   data-i18n-ph    -> atribut placeholder
   data-i18n-title -> atribut title */
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPh));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  document.documentElement.lang = activeLang;
}

function setLang(kode) {
  if (!I18N[kode]) return;
  activeLang = kode;
  try {
    localStorage.setItem(I18N_LANG_KEY, kode);
  } catch (e) {
    /* Tidak bisa disimpan: pilihannya tetap berlaku untuk sesi ini. */
  }
  applyI18n();
  /* Layar yang isinya dibuat dari JS tidak ikut tersapu applyI18n --
     applyI18n cuma mengisi elemen ber-data-i18n yang SUDAH ada di
     halaman. Kartu jadwal, label per-buku (MODE_LABELS), dan daftar HS
     Code semuanya dirakit dari string, jadi harus digambar ulang. */
  if (typeof applyModeLabels === "function") applyModeLabels();
  /* Label yang bergantung MODA (Nama Vessel/Voyager, No. Flight/Voyage,
     Pelabuhan/Terminal) ditulis dari JS, bukan lewat data-i18n --
     menandainya di HTML justru akan menimpanya dengan teks generik
     yang tidak sadar moda. */
  if (typeof applyTransportLabels === "function") applyTransportLabels();
  if (typeof render === "function") render();
  if (typeof renderHsCodes === "function") {
    const layar = document.getElementById("viewHsCode");
    if (layar && !layar.classList.contains("d-none")) renderHsCodes();
  }
  document.querySelectorAll("[data-lang-pick]").forEach((el) => {
    el.classList.toggle("active", el.dataset.langPick === kode);
  });
}

/* PENGKABELAN.

   Berkas ini dimuat di ujung <body>, jadi elemennya sudah terbaca --
   tidak perlu menunggu DOMContentLoaded.

   Dijaga `typeof document`: berkas ini juga dimuat oleh uji mesin
   (qa/engine-test.js) yang berjalan TANPA DOM, karena berkas lain di
   sana memanggil t() saat dimuat. Kamus & t() tetap berguna di sana;
   yang tidak berlaku cuma pengkabelan tombolnya. */
if (typeof document !== "undefined") {
  document.addEventListener("click", (e) => {
    const tombol = e.target.closest("[data-lang-pick]");
    if (!tombol) return;
    e.preventDefault();
    setLang(tombol.dataset.langPick);
  });

  /* Disapu sekali saat mulai: tanpa ini pilihan yang tersimpan dari
     kunjungan sebelumnya baru berlaku setelah tombolnya ditekan lagi. */
  applyI18n();
  document.querySelectorAll("[data-lang-pick]").forEach((el) => {
    el.classList.toggle("active", el.dataset.langPick === activeLang);
  });
}
